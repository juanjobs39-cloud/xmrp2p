export type Lang = "es" | "en";
export type Key = Exclude<keyof Dict, "pw_strength">;

let lang: Lang = /^es\b/i.test(globalThis.navigator?.language ?? "") ? "es" : "en";

export function setLang(l: Lang | undefined): void {
  if (l === "es" || l === "en") lang = l;
}
export function getLang(): Lang {
  return lang;
}
export function t(k: Key, vars: Record<string, string | number> = {}): string {
  const s = (lang === "es" ? es : en)[k] as string;
  return s.replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ""));
}
export function strength(score: number): string {
  return (lang === "es" ? es : en).pw_strength[Math.max(0, Math.min(4, score))];
}
